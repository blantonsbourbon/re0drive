#!/bin/sh
# RE0Drive NAS drop-in deploy (POSIX sh). No compile; pulls multi-arch image from GHCR.
# Usage:
#   ./scripts/deploy.sh
#   RE0DRIVE_TAG=0.1.0 ./scripts/deploy.sh
#   RE0DRIVE_DIR=/opt/re0drive RE0DRIVE_TAG=latest ./scripts/deploy.sh
#   DEPLOY_DRY_RUN=1 ./scripts/deploy.sh
#   curl -fsSL -H "Authorization: Bearer $GH_TOKEN" \
#     https://raw.githubusercontent.com/blantonsbourbon/re0drive/main/scripts/deploy.sh | sh -s --
#
# Env:
#   RE0DRIVE_DIR   install directory (default: $PWD/re0drive if cwd has no compose.yaml, else $PWD)
#   RE0DRIVE_TAG   image tag (default: latest)
#   RE0DRIVE_IMAGE full image ref (overrides TAG)
#   GH_USER / GH_TOKEN  optional auto docker login ghcr.io
#   SKIP_LOGIN=1   do not prompt for docker login
#   DEPLOY_DRY_RUN=1  create files and print actions only

set -eu

IMAGE_REPO="ghcr.io/blantonsbourbon/re0drive"

log() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

arch_ok() {
  u=$(uname -m 2>/dev/null || echo unknown)
  case "$u" in
    aarch64|arm64|x86_64|amd64) log "host arch: $u (supported)" ;;
    *) log "warning: uname -m=$u — image is linux/amd64+arm64; continue anyway" ;;
  esac
}

resolve_dir() {
  if [ -n "${RE0DRIVE_DIR:-}" ]; then
    printf '%s\n' "$RE0DRIVE_DIR"
    return
  fi
  if [ -f ./compose.yaml ] || [ -f ./docker-compose.yml ]; then
    pwd
    return
  fi
  printf '%s\n' "$(pwd)/re0drive"
}

image_ref() {
  if [ -n "${RE0DRIVE_IMAGE:-}" ]; then
    printf '%s\n' "$RE0DRIVE_IMAGE"
    return
  fi
  tag="${RE0DRIVE_TAG:-latest}"
  printf '%s\n' "${IMAGE_REPO}:${tag}"
}

write_compose() {
  dest="$1/compose.yaml"
  if [ -f "$dest" ]; then
    log "keep existing $dest"
    return
  fi
  cat >"$dest" <<'YAML'
services:
  re0drive:
    # Prebuilt multi-arch image (linux/amd64 + linux/arm64).
    image: ${RE0DRIVE_IMAGE:-ghcr.io/blantonsbourbon/re0drive:latest}
    # Optional local build: uncomment and run `docker compose up -d --build`
    # build: .
    restart: unless-stopped
    ports:
      - "${RE0DRIVE_HOST_BIND:-0.0.0.0}:8787:8787"
    environment:
      TZ: ${TZ:-Asia/Hong_Kong}
      RE0_GATEWAY_URL: ${RE0_GATEWAY_URL:-https://re0.tgtodrive.top}
      RE0_GATEWAY_SECRET: ${RE0_GATEWAY_SECRET:-}
      RE0DRIVE_COOKIE_SECURE: ${RE0DRIVE_COOKIE_SECURE:-0}
    volumes:
      - re0drive-data:/data
    stop_grace_period: 3m
    healthcheck:
      test: ["CMD", "curl", "-fsS", "http://127.0.0.1:8787/health"]
      interval: 30s
      timeout: 3s
      retries: 5
      start_period: 15s
volumes:
  re0drive-data:
YAML
  log "wrote $dest"
}

write_env() {
  dest="$1/.env"
  img="$2"
  if [ -f "$dest" ]; then
    if [ -n "${RE0DRIVE_TAG:-}${RE0DRIVE_IMAGE:-}" ]; then
      if grep -q '^RE0DRIVE_IMAGE=' "$dest" 2>/dev/null; then
        tmp="$dest.tmp.$$"
        sed "s|^RE0DRIVE_IMAGE=.*|RE0DRIVE_IMAGE=${img}|" "$dest" >"$tmp"
        mv "$tmp" "$dest"
        log "updated RE0DRIVE_IMAGE in $dest → $img"
      else
        printf '\nRE0DRIVE_IMAGE=%s\n' "$img" >>"$dest"
        log "appended RE0DRIVE_IMAGE=$img to $dest"
      fi
    else
      log "keep existing $dest"
    fi
    return
  fi
  cat >"$dest" <<EOF
# Generated by scripts/deploy.sh — no secrets. Edit as needed; do not commit.
RE0DRIVE_IMAGE=${img}
# LAN access from phones/PCs on the same network:
RE0DRIVE_HOST_BIND=0.0.0.0
TZ=Asia/Hong_Kong
# Set to 1 when the UI is reached over HTTPS via a reverse proxy:
RE0DRIVE_COOKIE_SECURE=0
# Only applied when the data volume is first created:
RE0_GATEWAY_URL=https://re0.tgtodrive.top
RE0_GATEWAY_SECRET=
EOF
  log "wrote $dest (no secrets)"
}

docker_login_maybe() {
  if [ "${SKIP_LOGIN:-0}" = "1" ]; then
    return
  fi
  if [ "${DEPLOY_DRY_RUN:-0}" = "1" ]; then
    log "[dry-run] would ensure docker login ghcr.io"
    return
  fi
  if [ -n "${GH_TOKEN:-}" ]; then
    user="${GH_USER:-${GITHUB_USER:-}}"
    if [ -z "$user" ]; then
      die "GH_TOKEN set but GH_USER (GitHub username) is empty"
    fi
    log "docker login ghcr.io as $user (token from env)"
    printf '%s\n' "$GH_TOKEN" | docker login ghcr.io -u "$user" --password-stdin
    return
  fi
  if docker manifest inspect "${IMAGE_REPO}:latest" >/dev/null 2>&1 \
      || docker buildx imagetools inspect "${IMAGE_REPO}:latest" >/dev/null 2>&1; then
    log "ghcr access ok (already logged in or package public)"
    return
  fi
  if [ ! -t 0 ]; then
    die "ghcr.io login required for private package; set GH_USER+GH_TOKEN or run interactively"
  fi
  log "Private GHCR package — log in (PAT with read:packages as password)."
  printf 'GitHub username: ' >&2
  read -r user
  [ -n "$user" ] || die "username required"
  docker login ghcr.io -u "$user"
}

wait_health() {
  url="http://127.0.0.1:8787/health"
  i=0
  while [ "$i" -lt 60 ]; do
    if curl -fsS "$url" >/dev/null 2>&1; then
      log "health ok: $url"
      return 0
    fi
    i=$((i + 1))
    sleep 1
  done
  die "service did not become healthy within 60s — check: docker compose logs --tail=80"
}

compose() {
  if docker compose version >/dev/null 2>&1; then
    docker compose "$@"
  elif have docker-compose; then
    docker-compose "$@"
  else
    die "docker compose not found"
  fi
}

main() {
  arch_ok
  dir=$(resolve_dir)
  img=$(image_ref)
  log "install dir: $dir"
  log "image:       $img"

  mkdir -p "$dir"
  write_compose "$dir"
  write_env "$dir" "$img"

  if [ "${DEPLOY_DRY_RUN:-0}" = "1" ]; then
    log "[dry-run] skip docker login / pull / up"
    log "[dry-run] would run: cd $dir && docker compose pull && docker compose up -d"
    log "[dry-run] files:"
    ls -la "$dir/compose.yaml" "$dir/.env"
    exit 0
  fi

  have docker || die "docker not found"
  have curl || die "curl not found (needed for health check)"

  docker_login_maybe

  cd "$dir"
  export RE0DRIVE_IMAGE="$img"
  log "pulling…"
  compose pull
  log "starting…"
  compose up -d
  wait_health

  lan=""
  if have hostname; then
    lan=$(hostname -I 2>/dev/null | awk '{print $1}') || true
  fi
  log ""
  log "RE0Drive is up."
  log "  local:  http://127.0.0.1:8787"
  if [ -n "$lan" ]; then
    log "  lan:    http://${lan}:8787"
  else
    log "  lan:    http://<NAS-IP>:8787"
  fi
  log "First visit: create admin → signing key → 115 QR → RE0 authorize → machine token."
  log "Update later: re-run this script (data volume is kept)."
}

main "$@"
